#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = create_builder();

    let tauri_app_builder = tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_window_state::Builder::new().build())
        .plugin(
            tauri_plugin_log::Builder::default()
                .level(log::LevelFilter::Info)
                .targets([
                    Target::new(TargetKind::Stdout),
                    Target::new(TargetKind::Webview),
                ])
                .build(),
        );

    tauri_app_builder
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);

            // Initialize project configuration
            let project_config = ProjectConfig::new().expect("Failed to initialize project config");
            let current_slug = project_config.get_current_project();

            // Try to load Sacrum config for the current project from global config
            let sacrum_config = current_slug.as_deref().and_then(|slug| {
                match SacrumConfig::load_for_project(slug) {
                    Ok(config) => {
                        log::info!(
                            "Found Sacrum config for project '{}' with ID: {}",
                            slug,
                            config.project_id
                        );
                        Some(config)
                    }
                    Err(e) => {
                        log::info!("Failed to load config for project '{}': {}", slug, e);
                        None
                    }
                }
            });

            let (service, client_arc) = match sacrum_config.as_ref() {
                Some(config) => {
                    let client = GraphqlClient::new(config.clone());
                    let client_arc = std::sync::Arc::new(client);
                    let services = vertebrae_sacrum_client::from_sacrum(client_arc.clone());
                    (Some(services), Some(client_arc))
                }
                None => (None, None),
            };

            // Manage application state with optional services
            app.manage(AppState {
                services: RwLock::new(service),
                sacrum_client: RwLock::new(client_arc),
                project_config,
            });

            // Initialize shared local chat session managers for JSONL chat
            let claude_manager = ClaudeSessionManager::new();
            let local_chat_manager =
                LocalChatSessionManager::with_default_harnesses(claude_manager.clone());
            app.manage(claude_manager);
            app.manage(local_chat_manager);
            log::info!("[STARTUP] Claude session manager initialized");

            // Start WebSocket connection to Sacrum for real-time updates
            let socket = if let Some(config) = sacrum_config {
                log::info!("[STARTUP] Starting WebSocket connection to Sacrum");
                let mut socket = websocket_client::SacrumSocket::new(
                    config.base_url,
                    config.api_token,
                    config.project_id,
                );
                socket.connect(app.handle());
                socket
            } else {
                log::info!("[STARTUP] No project config available, WebSocket starts disconnected");
                websocket_client::SacrumSocket::disconnected()
            };
            // Always manage socket so the command can access it.
            // Wrapped in a Mutex so set_current_project can swap it out when the
            // user selects a different project at runtime.
            app.manage(tokio::sync::Mutex::new(socket));

            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn builder_exports_task_run_command_bindings() {
        let dir = tempfile::tempdir().expect("create temp dir");
        let output = dir.path().join("bindings.ts");

        create_builder()
            .export(Typescript::default(), &output)
            .expect("export bindings");

        let bindings = std::fs::read_to_string(output).expect("read generated bindings");
        for command in [
            "async getActiveRun(",
            "async getTaskRuns(",
            "async getTaskRunTrace(",
            "async runWorkflow(",
            "async stopRun(",
            "async orchestrateTask(",
            "async stopOrchestrator(",
            "async getSupportedLocalChatHarnesses(",
            "async createLocalChatSession(",
            "async sendLocalChatMessage(",
            "async closeLocalChatSession(",
        ] {
            assert!(
                bindings.contains(command),
                "generated bindings should include {command}"
            );
        }

        assert!(
            bindings.contains("taskRunChangedEvent: TaskRunChangedEvent"),
            "generated bindings should include the TaskRun changed event"
        );
        assert!(
            bindings.contains("localChatSessionInitEvent: LocalChatSessionInitEvent"),
            "generated bindings should include the neutral local chat init event"
        );
        for ty in [
            "export type LocalChatHarnessKind",
            "export type LocalChatHarnessCatalog",
            "export type CreateLocalChatSessionInput",
            "export type LocalChatSessionError",
        ] {
            assert!(
                bindings.contains(ty),
                "generated bindings should include {ty}"
            );
        }
    }
}
