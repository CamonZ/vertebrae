#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = create_builder();

    let tauri_app_builder = tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_updater::Builder::new().build())
        .plugin(tauri_plugin_window_state::Builder::new().build())
        .plugin(
            tauri_plugin_log::Builder::default()
                .level(log::LevelFilter::Info)
                .targets([
                    Target::new(TargetKind::Stdout),
                    Target::new(TargetKind::Webview).format(|out, message, record| {
                        out.finish(format_args!("[{}] {}", record.target(), message));
                    }),
                ])
                .build(),
        );

    tauri_app_builder
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);

            // Keep the provider-neutral managed skill bundle outside project
            // initialization. Provider integrations discover this app-data
            // root directly and never need project-local skill links.
            match provision_managed_skills() {
                Ok((root, installed)) => log::info!(
                    "[STARTUP] Staged {installed} managed skill files in {}",
                    root.display()
                ),
                Err(error) => log::warn!("[STARTUP] Failed to stage managed skills: {error}"),
            }

            // Initialize project configuration
            let project_config = ProjectConfig::new().expect("Failed to initialize project config");
            let current_slug = project_config.get_current_project();
            let compatibility_working_dir = current_slug
                .as_deref()
                .and_then(|slug| {
                    project_config
                        .get_projects()
                        .into_iter()
                        .find(|project| project.slug == slug)
                })
                .map(|project| PathBuf::from(project.path))
                .or_else(|| std::env::current_dir().ok())
                .unwrap_or_else(|| PathBuf::from("."));
            let claude_startup_capabilities =
                ClaudeStartupCapabilities::resolve(&compatibility_working_dir);
            match (
                &claude_startup_capabilities.plugin_resolution.plugin_root,
                &claude_startup_capabilities.plugin_resolution.warning,
            ) {
                (Some(plugin_root), _) => log::info!(
                    "[STARTUP] Cached Claude installed-skill compatibility: {}",
                    plugin_root.display()
                ),
                (None, Some(warning)) => {
                    log::warn!("[STARTUP] Cached Claude installed-skill compatibility: {warning}")
                }
                (None, None) => {
                    log::info!("[STARTUP] Cached Claude installed-skill compatibility: unavailable")
                }
            }
            log::info!(
                "[STARTUP] Claude provider, compatibility, and skill discovery are cached until restart"
            );

            // Try to load Sacrum config for the current project from global config
            let sacrum_config = current_slug.as_deref().and_then(|slug| {
                match SacrumConfig::load_for_project(slug) {
                    Ok(config) => {
                        log::info!(
                            "Found Sacrum config for project '{}' with ID: {}",
                            slug,
                            config.project_id
                        );
                        Some(config)
                    }
                    Err(e) => {
                        log::info!("Failed to load config for project '{}': {}", slug, e);
                        None
                    }
                }
            });

            let (service, client_arc) = match sacrum_config.as_ref() {
                Some(config) => {
                    let client = GraphqlClient::new(config.clone());
                    let client_arc = std::sync::Arc::new(client);
                    let services = vertebrae_sacrum_client::from_sacrum(client_arc.clone());
                    (Some(services), Some(client_arc))
                }
                None => (None, None),
            };

            // Manage application state with optional services
            app.manage(AppState {
                services: RwLock::new(service),
                sacrum_client: RwLock::new(client_arc),
                project_config,
            });

            // Initialize local chat session manager (owns Claude + Codex harnesses)
            let local_chat_manager =
                LocalChatSessionManager::with_claude_startup_capabilities(
                    claude_startup_capabilities,
                );
            app.manage(local_chat_manager);
            log::info!("[STARTUP] Local chat session manager initialized");

            // Start WebSocket connection to Sacrum for real-time updates
            let socket = if let Some(config) = sacrum_config {
                log::info!("[STARTUP] Starting WebSocket connection to Sacrum");
                let mut socket = websocket_client::SacrumSocket::new(
                    config.base_url,
                    config.api_token,
                    config.project_id,
                );
                socket.connect(app.handle());
                socket
            } else {
                log::info!("[STARTUP] No project config available, WebSocket starts disconnected");
                websocket_client::SacrumSocket::disconnected()
            };
            // Always manage socket so the command can access it.
            // Wrapped in a Mutex so set_current_project can swap it out when the
            // user selects a different project at runtime.
            app.manage(tokio::sync::Mutex::new(socket));

            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}

fn provision_managed_skills() -> Result<(PathBuf, usize), String> {
    let root =
        vertebrae_installer::provision_installed_skills_dir().map_err(|error| error.to_string())?;
    let installed = vertebrae_skills_assets::install_embedded_skills(&root)
        .map_err(|error| error.to_string())?;
    Ok((root, installed))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn builder_exports_task_run_command_bindings() {
        let dir = tempfile::tempdir().expect("create temp dir");
        let output = dir.path().join("bindings.ts");

        create_builder()
            .export(Typescript::default(), &output)
            .expect("export bindings");

        let bindings = std::fs::read_to_string(output).expect("read generated bindings");
        for command in [
            "async getActiveRun(",
            "async getTaskRuns(",
            "async getTaskRunTrace(",
            "async runWorkflow(",
            "async stopRun(",
            "async orchestrateTask(",
            "async stopOrchestrator(",
            "async getSupportedLocalChatHarnesses(",
            "async createLocalChatSession(",
            "async sendLocalChatMessage(",
            "async closeLocalChatSession(",
            "async inferLocalChatSessionTitle(",
        ] {
            assert!(
                bindings.contains(command),
                "generated bindings should include {command}"
            );
        }

        assert!(
            bindings.contains("taskRunChangedEvent: TaskRunChangedEvent"),
            "generated bindings should include the TaskRun changed event"
        );
        assert!(
            bindings.contains("localChatSessionInitEvent: LocalChatSessionInitEvent"),
            "generated bindings should include the neutral local chat init event"
        );
        for ty in [
            "export type LocalChatHarnessKind",
            "export type LocalChatHarnessCatalog",
            "export type CreateLocalChatSessionInput",
            "export type InferLocalChatSessionTitleInput",
            "export type InferLocalChatSessionTitleOutput",
            "export type LocalChatSessionError",
        ] {
            assert!(
                bindings.contains(ty),
                "generated bindings should include {ty}"
            );
        }
    }

    #[test]
    fn managed_gui_skill_bundle_includes_artifact_skill() {
        let dir = tempfile::tempdir().expect("create temp dir");
        vertebrae_skills_assets::install_embedded_skills(dir.path())
            .expect("install embedded GUI skills");

        assert!(
            dir.path().join("vtb-artifact/SKILL.md").is_file(),
            "GUI managed skill bundle should include vtb-artifact"
        );
    }
}
