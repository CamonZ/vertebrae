/// Example command that will be exported with type definitions.
/// This serves as a template for future Tauri commands.
#[tauri::command]
#[specta::specta]
fn greet(name: String) -> String {
    format!("Hello, {}! You've been greeted from Rust!", name)
}

/// Export TypeScript bindings to the frontend src directory.
/// This function is called by the generate-types binary.
pub fn export_bindings() -> Result<(), Box<dyn std::error::Error>> {
    let builder = create_builder();
    builder.export(
        Typescript::default()
            .header("/* eslint-disable */\n// @ts-nocheck\n// This file was auto-generated by tauri-specta. Do not edit."),
        "../src/bindings.ts",
    )?;
    Ok(())
}

/// Create the tauri-specta builder with all commands and events registered.
