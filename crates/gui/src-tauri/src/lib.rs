/// Example command that will be exported with type definitions.
/// This serves as a template for future Tauri commands.
#[tauri::command]
#[specta::specta]
fn greet(name: String) -> String {
    format!("Hello, {}! You've been greeted from Rust!", name)
}

/// Export TypeScript bindings to the frontend src directory.
/// This function is called by the generate-types binary.
pub fn export_bindings() -> Result<(), Box<dyn std::error::Error>> {
    let builder = create_builder();
    builder.export(
        Typescript::default()
            .header("/* eslint-disable */\n// @ts-nocheck\n// This file was auto-generated by tauri-specta. Do not edit."),
        "../src/bindings.ts",
    )?;
    Ok(())
}

/// Create the tauri-specta builder with all commands and events registered.
fn create_builder() -> Builder {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            greet,
            // Project management commands
            commands::get_projects,
            commands::add_project,
            commands::remove_project,
            commands::get_current_project,
            commands::set_current_project,
            commands::has_project_selected,
            // Task commands
            commands::list_tasks,
            commands::get_task,
            commands::get_task_hierarchy,
            // Task relationship commands
            commands::set_parent,
            commands::remove_parent,
            commands::add_dependency,
            commands::remove_dependency,
            // Task mutation commands
            commands::create_task,
            commands::update_task,
            commands::assign_workflow,
            // Task deletion command
            commands::delete_task,
            // Workflow commands
            commands::list_workflows,
            commands::get_workflow,
            commands::get_workflow_with_tasks,
            commands::get_workflow_with_task_details,
            commands::list_workflow_transitions,
            // Execution commands
            commands::get_task_executions,
            commands::get_execution_logs,
            // Step commands (first-class workflow steps)
            commands::list_steps_for_workflow,
            commands::get_step,
            // Workflow execution commands
            commands::run_workflow,
            // PTY commands
            commands::create_pty_session,
            commands::write_pty,
            commands::resize_pty,
            commands::close_pty_session,
            // Chat session commands
            commands::create_chat_session,
            commands::get_chat_session,
            commands::list_chat_sessions,
            commands::end_chat_session,
            commands::update_chat_session_title,
            commands::add_chat_message,
            commands::get_chat_messages,
            commands::get_chat_session_content,
            commands::delete_chat_session,
        ])
        .events(collect_events![
            TaskChangedEvent,
            WorkflowChangedEvent,
            WorkflowExecutionEvent,
            PtyOutputEvent,
            PtyExitEvent
        ])
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = create_builder();

    let mut tauri_app_builder = tauri::Builder::default().plugin(tauri_plugin_dialog::init());

    if cfg!(debug_assertions) {
        tauri_app_builder = tauri_app_builder.plugin(
            tauri_plugin_log::Builder::default()
                .level(log::LevelFilter::Info)
                .build(),
        );
    }

    tauri_app_builder
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);

            // Start HTTP notification server for CLI mutations
            let app_handle = app.handle().clone();
            notification_server::start_notification_server(
                app_handle,
                notification_server::DEFAULT_NOTIFICATION_PORT,
            );
            log::info!(
                "[STARTUP] Notification server started on 127.0.0.1:{}",
                notification_server::DEFAULT_NOTIFICATION_PORT
            );

            // Initialize project configuration
            let project_config = ProjectConfig::new().expect("Failed to initialize project config");

            // Check if there's a current project set
            let current_project = project_config.get_current_project();
            let service = if let Some(ref project_path) = current_project {
                let db_path = PathBuf::from(project_path).join(".vtb/data");
                log::info!("Connecting to database at: {:?}", db_path);

                tauri::async_runtime::block_on(async {
                    match Database::connect(&db_path).await {
                        Ok(db) => {
                            if let Err(e) = db.init().await {
                                log::error!("Failed to initialize database: {}", e);
                                None
                            } else {
                                Some(DefaultTaskService::new(db))
                            }
                        }
                        Err(e) => {
                            log::error!("Failed to connect to database: {}", e);
                            None
                        }
                    }
                })
            } else {
                log::info!("No project selected, starting without database connection");
                None
            };

            // Manage application state with optional task service
            app.manage(AppState {
                service: RwLock::new(service),
                project_config,
            });

            // Initialize PTY manager for terminal sessions
            app.manage(PtyManager::new());
            log::info!("[STARTUP] PTY manager initialized");

            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
