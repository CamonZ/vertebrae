/* ──────────────────────────────────────────────────────────────────
   Vertebrae · Hearth — Workflow graph: SINGLE SOURCE OF TRUTH
   Both the Atlas (map) and the Graph (topology) pages render from THIS.

   Model
   ─────
   • workflows[]      one entry per workflow; `steps[]` are its real nodes.
   • edges[]          every transition is STEP-LEVEL: "wfId.stepId".
                        - cross-workflow  → from.wf !== to.wf
                        - loop-back       → same wf, target step earlier in order
                      Forward step→step links are implied by step order and
                      generated by the layout helper (not listed here).

   Derived elsewhere (never hand-placed):
   • Graph page  = ELK nested layout of workflows⊃steps + these edges.
   • Atlas page  = ELK layered layout of the *condensed* graph (edges
                   aggregated up to workflow→workflow). ELK layers become
                   the value-stream columns.
   ────────────────────────────────────────────────────────────────── */
(function () {
  const wf = (id, name, status, statusLabel, desc, steps, extra) =>
    Object.assign({ id, name, status, statusLabel, desc, steps }, extra || {});
  const s = (id, name, kind, role) => ({ id, name, kind, role });

  const workflows = [
    wf('decomposition', 'Decomposition', 'plan', 'Planning',
      '1-level decomposition. Split a parent unit of work into immediate children, then route each onward.',
      [s('decompose', 'decompose', 'entry', 'entry'), s('eval', 'eval', 'eval', 'process'), s('route', 'route', 'route', 'exit')], { phase: 'Intake', runs24h: 8, avg: '1m 12s' }),

    wf('backlog', 'Backlog', 'plan', 'Default',
      'Default intake for new tickets. Triage from the inbox, evaluate, and route to the right pipeline.',
      [s('inbox', 'inbox', 'entry', 'entry'), s('eval', 'eval', 'eval', 'process'), s('route', 'route', 'route', 'exit')], { phase: 'Intake', runs24h: 34, avg: '0m 40s', running: 1 }),

    wf('verification', 'Verification', 'review', 'Review',
      "Level-agnostic alignment check. Compares a parent's shipped children against intent; on gaps, spawns corrective children.",
      [s('align', 'align', 'entry', 'entry'), s('eval', 'eval', 'eval', 'process'), s('route', 'route', 'route', 'exit')], { phase: 'Verify', runs24h: 12, avg: '2m 30s' }),

    wf('scaffold', 'Scaffold', 'progress', 'In Progress',
      'Create worktree + draft PR for a ticket, stamp the worktree on the ticket and all its children.',
      [s('create_workspace', 'create_workspace', 'entry', 'entry'), s('create_draft_pr', 'create_draft_pr', 'execute', 'process'),
       s('stamp_children', 'stamp_children', 'execute', 'process'), s('eval', 'eval', 'eval', 'process'), s('route', 'route', 'route', 'exit')], { phase: 'Build', runs24h: 14, avg: '0m 52s', running: 1 }),

    wf('implementation', 'Implementation', 'progress', 'In Progress',
      'Task implementation loop: set up workspace, write tests, implement, simplify, verify locally, then route on.',
      [s('setup_workspace', 'setup_workspace', 'entry', 'entry'), s('write_tests', 'write_tests', 'execute', 'process'),
       s('implement', 'implement', 'execute', 'process'), s('simplify', 'simplify', 'execute', 'process'),
       s('local_verify', 'local_verify', 'eval', 'process'), s('route', 'route', 'route', 'exit')], { phase: 'Build', runs24h: 9, avg: '11m 20s', running: 2 }),

    wf('humanReview', 'Human Review', 'human', 'Human',
      'Holding queue for tickets that need human attention. A person manually re-assigns the ticket onward.',
      [s('wait', 'wait', 'human', 'entry/exit')], { phase: 'Review', runs24h: 6, avg: '38m 04s' }),

    wf('ship', 'Ship', 'progress', 'Shipping',
      'Ticket-only txn after Verification passes: mark PR ready, wait for CI, merge, tear down worktree and branch.',
      [s('mark_ready', 'mark_ready', 'execute', 'entry'), s('wait_ci', 'wait_ci', 'execute', 'process'),
       s('merge', 'merge', 'execute', 'process'), s('teardown', 'teardown', 'execute', 'process'),
       s('eval', 'eval', 'eval', 'process'), s('route', 'route', 'route', 'exit')], { phase: 'Ship', runs24h: 11, avg: '3m 18s', running: 1 }),

    wf('waitForChildren', 'WaitForChildren', 'active', 'Active',
      'Park a parent (epic or ticket) until all its children reach done, then route to Verification.',
      [s('wait', 'wait', 'wait', 'entry'), s('eval', 'eval', 'eval', 'process'), s('route', 'route', 'route', 'exit')], { live: true, phase: 'Verify', runs24h: 5, avg: '— waiting', running: 1 }),

    wf('finalizer', 'Implementation Finalizer', 'progress', 'In Progress',
      'Task-level jj change finalization after implementation verification passes. Each task owns a separate jj change.',
      [s('commit', 'commit', 'execute', 'entry'), s('eval', 'eval', 'eval', 'process'), s('route', 'route', 'route', 'exit')], { phase: 'Build', runs24h: 9, avg: '0m 48s' }),

    wf('done', 'done', 'review', 'Final',
      'Terminal sink. Units of work that have shipped and verified end here.',
      [s('done', 'done', 'final', 'entry/exit')], { phase: 'Ship', runs24h: 22, avg: '—' }),
  ];

  /* step-level transitions (forward intra-step links are generated by the layout helper) */
  const E = (from, to, label) => ({ from, to, label });
  const edges = [
    // intake & decomposition
    E('backlog.route', 'decomposition.decompose', 'decompose'),
    E('decomposition.route', 'backlog.inbox', 'children-created'),   // re-route back to an earlier workflow
    E('backlog.route', 'scaffold.create_workspace', 'approve-ticket'),
    E('backlog.route', 'implementation.setup_workspace', 'approve-task'),
    E('backlog.route', 'verification.align', 'needs-review'),
    E('backlog.route', 'humanReview.wait', 'needs-human'),
    // build → forward
    E('scaffold.route', 'implementation.setup_workspace', 'scaffolded'),
    E('implementation.route', 'finalizer.commit', 'verified'),
    E('finalizer.route', 'waitForChildren.wait', 'await-children'),
    E('verification.route', 'ship.mark_ready', 'approve'),
    E('verification.route', 'waitForChildren.wait', 'corrective-children'),
    E('waitForChildren.route', 'verification.align', 'verify-parent'),  // re-route back up
    // escalation to human — every workflow except `done` can route to Human Review
    E('decomposition.route', 'humanReview.wait', 'needs-human'),
    E('scaffold.route', 'humanReview.wait', 'needs-human'),
    E('implementation.route', 'humanReview.wait', 'needs-human'),
    E('verification.route', 'humanReview.wait', 'needs-human'),
    E('finalizer.route', 'humanReview.wait', 'needs-human'),
    E('ship.route', 'humanReview.wait', 'needs-human'),
    E('waitForChildren.route', 'humanReview.wait', 'needs-human'),
    // human resuming — from Human Review a person can re-assign onward to any workflow
    E('humanReview.wait', 'decomposition.decompose', 'resume-decompose'),
    E('humanReview.wait', 'backlog.inbox', 'resume-backlog'),
    E('humanReview.wait', 'scaffold.create_workspace', 'resume-scaffold'),
    E('humanReview.wait', 'implementation.setup_workspace', 'resume-impl'),
    E('humanReview.wait', 'finalizer.commit', 'resume-finalize'),
    E('humanReview.wait', 'verification.align', 'resume-verify'),
    E('humanReview.wait', 'waitForChildren.wait', 'resume-wait'),
    E('humanReview.wait', 'ship.mark_ready', 'resume-ship'),
    E('humanReview.wait', 'done.done', 'resolve-done'),
    // sinks
    E('ship.route', 'done.done', 'complete'),
    E('waitForChildren.route', 'done.done', 'complete'),
    // intra-workflow loop-backs (route → an earlier step in the SAME workflow)
    E('backlog.route', 'backlog.eval', 're-eval'),
    E('scaffold.route', 'scaffold.create_draft_pr', 'retry'),
    E('implementation.route', 'implementation.implement', 'revise'),
    E('ship.route', 'ship.wait_ci', 're-check'),
  ];

  /* ──────────────────────────────────────────────────────────────
     Step configuration library — the per-step detail surfaced in the
     graph's Step inspector. Keyed by bare step id (steps of the same
     name share config across workflows). Fields mirror the canonical
     Step Configuration panel: goal · prompt (liquid templated) · model
     · agents · skills. (type = kind, order = index, transitions =
     derived from edges; those are NOT stored here.)
     ────────────────────────────────────────────────────────────── */
  const st = (o) => Object.assign({ goal: '', prompt: '', model: 'gpt-5.5:low', agents: [], skills: [] }, o);
  const stepLib = {
    decompose: st({ goal: 'Split a parent unit of work into immediate, independently-shippable children.', model: 'gpt-5.5:high', skills: ['decomposition'],
      prompt: 'Decompose ticket {{ task.id }} into immediate child units of work.\n\nParent: {{ task.title }}\n{% if task.spec %}Spec: {{ task.spec }}{% endif %}\n\nSteps:\n1. Read the parent intent and acceptance criteria.\n2. Propose 2–6 children, each independently shippable.\n3. Emit children with titles, specs, and a suggested workflow.' }),
    inbox: st({ goal: 'Triage new tickets arriving in the backlog inbox.',
      prompt: 'Triage incoming ticket {{ task.id }} from the backlog inbox.\n\nTitle: {{ task.title }}\n\nSteps:\n1. Classify: epic vs ticket vs task.\n2. Set priority and tags.\n3. Hand off to eval for routing.' }),
    align: st({ goal: "Compare a parent's shipped children against the original intent.", model: 'gpt-5.5:high', agents: ['.claude/agents/reviewer.md'], skills: ['verification'],
      prompt: "Check that {{ task.id }}'s shipped children satisfy the parent intent.\n\nParent: {{ task.title }}\n{% for child in task.children %}- {{ child.id }}: {{ child.title }}\n{% endfor %}\nFlag any gaps; where found, describe the corrective children to spawn." }),
    create_workspace: st({ goal: 'Create the git worktree that a ticket and its children will share.',
      prompt: 'Create a git worktree for ticket {{ task.id }}.\n\n1. cd into the repo root.\n2. `git worktree add {{ task.worktree }} -b {{ task.branch }}`.\n3. Stamp the worktree path back on the ticket.' }),
    create_draft_pr: st({
      prompt: 'Open a draft PR for ticket {{ task.id }} from {{ task.branch }}.\n\n`gh pr create --draft --base main --title {{ task.title }}`\n\nEmit the PR number and URL onto the handoff.' }),
    stamp_children: st({
      prompt: 'Stamp the worktree {{ task.worktree }} on {{ task.id }} and every child so the whole subtree shares one workspace.\n\n{% for child in task.children %}- stamp {{ child.id }}\n{% endfor %}' }),
    setup_workspace: st({ goal: 'Prepare a clean, building workspace for the task.',
      prompt: 'Set up the workspace for task {{ task.id }}.\n\n1. cd into {{ task.worktree }}.\n2. Install dependencies and confirm a clean build.\n3. Confirm the base branch is current.' }),
    write_tests: st({ model: 'gpt-5.5:high', agents: ['.claude/agents/coder.md'], skills: ['test-authoring'],
      prompt: 'Write failing tests that capture the intent of {{ task.id }} before any implementation.\n\nSpec: {{ task.spec }}\n\nCover the acceptance criteria. Keep tests minimal and behavioral — no implementation detail.' }),
    implement: st({ goal: 'Make the previously-written tests pass with the smallest correct change.', model: 'gpt-5.5:high', agents: ['.claude/agents/coder.md'], skills: ['code-review'],
      prompt: 'Implement {{ task.id }} until the tests from the previous step pass.\n\n{% if execution.handoff %}Handoff: {{ execution.handoff }}{% endif %}\n\nKeep changes scoped to the task. Do not refactor unrelated code.' }),
    simplify: st({ model: 'gpt-5.5:high', skills: ['code-review'],
      prompt: 'Simplify the implementation of {{ task.id }} without changing behavior.\n\nRemove dead code, tighten names, collapse needless indirection.\nThe full test suite must stay green.' }),
    local_verify: st({
      prompt: 'Run the full local check for {{ task.id }}.\n\n1. Run the test suite.\n2. Run lint + typecheck.\n3. Emit pass/fail with the first failing output, if any.' }),
    commit: st({ goal: 'Finalize the task-level jj change after verification passes.',
      prompt: 'Finalize the jj change for task {{ task.id }}.\n\n`jj commit -m {{ task.title }}`\n\nEach task owns a separate jj change — do not squash sibling changes together.' }),
    mark_ready: st({
      prompt: "Flip the draft PR for ticket {{ task.id }} to ready-for-review.\n\n{% if execution.handoff and execution.handoff.pr_url %}PR URL: {{ execution.handoff.pr_url }}\n{% endif %}{% if execution.handoff and execution.handoff.branch %}Branch: {{ execution.handoff.branch }}\n{% endif %}\nSteps:\n1. If the PR URL isn't in the handoff, resolve it: cd into the ticket's worktree ({{ task.worktree }}) and `gh pr view --json url,number,state`.\n2. Push any unpushed commits: `git push`.\n3. `gh pr ready <PR#>` (idempotent — if already ready, reports no-op).\n4. Emit the PR URL and the latest HEAD SHA on the branch." }),
    wait_ci: st({
      prompt: "Wait for CI to finish on {{ task.id }}'s PR.\n\n`gh pr checks <PR#> --watch`\n\nOn green, continue to merge. On red, route back for a fix." }),
    merge: st({
      prompt: "Merge {{ task.id }}'s PR once CI is green and review has approved.\n\n`gh pr merge <PR#> --squash --delete-branch`\n\nConfirm the resulting merge commit SHA." }),
    teardown: st({
      prompt: 'Tear down the workspace for {{ task.id }} after merge.\n\n1. `git worktree remove {{ task.worktree }}`.\n2. Delete the branch {{ task.branch }}.\n3. Clear the worktree stamp on the ticket and its children.' }),
    eval: st({
      prompt: 'Evaluate the result of the previous step for {{ task.id }}.\n\n{% if execution.error %}Error: {{ execution.error }}{% endif %}\nDecide pass / fail and emit a short rationale the router can act on.' }),
    route: st({
      prompt: 'Route {{ task.id }} to its next workflow based on the eval verdict.\n\n{% if eval.passed %}Forward along the success path.{% else %}Send back for revision, or escalate to human.{% endif %}\nEmit exactly one transition.' }),
    wait: st({ model: null,
      prompt: "Hold {{ task.id }} until its gate clears.\n\n{% if task.kind == 'parent' %}Wait for every child to reach done, then route to Verification.{% else %}Wait for a human to re-assign this ticket onward.{% endif %}" }),
    done: st({ model: null,
      prompt: 'Terminal sink — no prompt. Units of work that have shipped and verified come to rest here.' }),
  };

  /* value-stream phases, in flow order — the Atlas columns come from THESE
     (each workflow's `phase` above), not from the layout engine's layer index. */
  const phases = ['Intake', 'Build', 'Verify', 'Review', 'Ship'];

  window.WFGraph = { workflows, edges, phases, stepLib };
})();
